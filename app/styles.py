def is_known_style(style: str) -> bool:
    """Проверка, что переданное имя стиля присутствует в реестре."""
    return style in STYLE_TO_COLUMN


def style_column(style: str) -> str:
    """Колонка st1..st9 для стиля; None, если стиль неизвестен."""
    return STYLE_TO_COLUMN.get(style)


